-- PROBE 그리기 0.1.2 -- 글자 수와 한글을 가른다
--
-- 0.1.1 이 밝힌 것
-- ---------------------------------------------------------------------------
-- 좌표계는 **정상**이었다.  20 px 격자를 한 글자씩 찍으니 x=0 부터 260 까지 전부
-- 보였고, 네 귀퉁이 사각형도 제자리에 왔고, 게임 화면과 정확히 겹쳤다.
--
-- 그러면 0.1.0 에서 왼쪽 ASCII 가 안 보인 이유는 좌표가 아니다.  차이는 하나뿐이다:
--
--     0.1.0  "ASCII OK 12345"  여러 글자 · 공백 포함     안 보임
--     0.1.1  "3"               한 글자                   보임
--     0.1.0  "TOP-RIGHT"       여러 글자 · 공백 없음      보임 (세로로)
--
-- **공백이 있는 문자열이 안 보였다.**  그리고 보인 것도 세로로 줄바꿈됐다.
-- Mesen 의 drawString 이 문자열을 어떻게 다루는지 -- 줄바꿈·공백·길이 --
-- 를 갈라서 확인한다.
--
-- 무엇을 그리나
-- ---------------------------------------------------------------------------
--     A  한 글자                     기준선.  0.1.1 에서 보인 것
--     B  공백 없는 여러 글자
--     C  공백 있는 여러 글자          <- 0.1.0 에서 실패한 형태
--     D  한글 한 글자                 폰트에 한글이 있는가
--     E  한글 여러 글자
--     F  실제 자막 문장                최종 목표
--
-- 각 줄을 y 를 벌려 그리고, 앞에 번호를 붙여 어느 줄이 살았는지 바로 알게 한다.

local LINES = {
  {40,  "A", "X"},
  {56,  "B", "ABCDEFGH"},
  {72,  "C", "ABC DEF GHI"},
  {88,  "D", "한"},
  {104, "E", "한글테스트"},
  {120, "F", "길리언 시드님."},
  {136, "G", "금일부로 JUNKER로 임명된 길리언 시드다."},
}

local function draw()
  for _, item in ipairs(LINES) do
    local y, tag, text = item[1], item[2], item[3]
    -- 번호는 공백 없이 한 글자.  이건 0.1.1 에서 확실히 보인 형태다
    emu.drawString(4, y, tag, 0x00FF00, 0xC0000000, 2)
    emu.drawString(20, y, text, 0xFFFFFF, 0xC0000000, 2)
  end
end

emu.addEventCallback(draw, emu.eventType.endFrame)

emu.log("PROBE 그리기 0.1.2 -- 글자 수·공백·한글을 가른다")
emu.log("  y=40  A  X                  한 글자")
emu.log("  y=56  B  ABCDEFGH           공백 없는 여러 글자")
emu.log("  y=72  C  ABC DEF GHI        공백 있는 여러 글자")
emu.log("  y=88  D  한                  한글 한 글자")
emu.log("  y=104 E  한글테스트           한글 여러 글자")
emu.log("  y=120 F  길리언 시드님.        실제 자막 (짧은 것)")
emu.log("  y=136 G  금일부로 JUNKER...   실제 자막 (긴 것)")
emu.log("")
emu.log("  왼쪽 초록 글자(A~G)는 다 보여야 한다.  그 오른쪽이 보이는지를 볼 것")
