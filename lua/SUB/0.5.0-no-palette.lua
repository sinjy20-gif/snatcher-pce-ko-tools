-- SUB 0.5.0 -- 이분 ③: VCE 팔레트 쓰기만 뺀다.
--
-- 여기까지
-- ---------------------------------------------------------------------------
--     0.4.97  와이프 없음          -> 증상 남음   (와이프 무죄)
--     0.4.99  그리기 없음          -> 증상 사라짐 (적재/RAM 쓰기 무죄)
--
-- 즉 원인은 "우리가 그리는 것" 안에 있다.  그 안에 넷이 있다:
--
--     A1  $5B80 점유    엔진이 게임 스크립트 VM 데이터 스택에 복사된다
--     A2  VRAM 전송     글리프 -> $1600
--     A3  SATB 푸시     게임 $6463 루프로 19 칸
--     A4  VCE 팔레트    stage 루틴이 $0402-$0405 에 쓴다   ← 이 판이 끊는 것
--
-- 왜 A4 부터인가
-- ---------------------------------------------------------------------------
--   · stage 루틴은 **조각마다 한 번** 돈다.  번쩍임 주기와 같다
--   · 한 글자 엔진(0.4.87)에서 안 줄었다.  글자 수와 무관한 고정 구간이다
--   · VDC 재무장(0.4.89)이 못 고쳤다.  우리가 보호한 것은 **VDC**($0000-$0003)고
--     이것은 **VCE**($0402-$0405) 다.  다른 칩이고, 이 루틴엔 인터럽트 보호가 없다
--   · VCE 도 주소 래치 + 자동증가다.  색 2 개(데이터 4 회)를 쓰고 나면 주소가
--     $01F3 에 남는다.  게임이 래스터 중에 자기 래치를 믿고 팔레트를 쓰면
--     엉뚱한 엔트리로 간다.  아래 띠를 검은 팔레트로 가려두는 방식이면
--     그 쓰기가 빗나가는 순간 가려둔 배경이 그대로 드러난다 -- 증상과 같다
--
-- 이 판
-- ---------------------------------------------------------------------------
-- stage 루틴 31 B 대신 **RTS 한 바이트**를 심는다.  entry 의 JSR 은 그대로
-- 안전하게 돌아오고, 덮인 글리프 비트맵을 실행하는 문제도 똑같이 막힌다.
-- 사라지는 것은 VCE 팔레트 초기화뿐이다.  A1·A2·A3 은 그대로 돈다.
--
-- 판정
--     번쩍임이 사라지면   ★ VCE 팔레트 경합 확정.  stage 를 보호하거나
--                         VBlank 로 옮기거나, 팔레트를 Lua 가 미리 세운다
--     그대로면            A4 무죄.  A1($5B80 점유) / A3(SATB 푸시) 로 간다
--
-- ★ 부작용: 팔레트 15 를 우리가 안 세우므로 **자막 글자가 안 보이거나 색이
--   이상할 수 있다.**  그건 예정된 것이다.  판정은 오직 "배경이 튀어나오는가".
--   엔진이 실제로 돌았는지는 PATCHED / STAGE REARM 로그로 확인한다.
