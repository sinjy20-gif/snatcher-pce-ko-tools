-- SUB 0.4.89-vdc-rearm -- 국장실 "위 그림이 중간중간 짧게 보이는" 증상 대조판.
--
-- 무엇을 보는 실험인가
-- ---------------------------------------------------------------------------
-- 0.4.87(한 글자 엔진)에서 두 증상이 갈렸다.
--
--     떨림        확실히 줄었다   -> 전송량 / 래스터 IRQ 지연
--     위 그림     그대로          -> 전송량이 원인이 아니다
--
-- 한 글자 패치는 글리프 루프 반복만 줄인다.  VDC 레지스터를 고르는 셋업 구간은
-- 조각마다 한 번씩 똑같이 실행되므로 전혀 줄지 않는다.  원본 엔진은 루프 밖에서
-- `ST0 #$02` 로 VWR 을 고른 뒤 **80 바이트** 를 더 가서야 첫 전송을 한다.  그
-- 사이 래스터 분할 IRQ 가 VDC 를 건드리면 선택 래치가 바뀌고, 남은 글리프
-- 데이터가 그 레지스터로 들어간다.  BYR 이면 세로 스크롤이 튀어 타일맵 위쪽이
-- 화면으로 끌려나온다.
--
-- 이 판의 엔진은 그 선택을 **TIA 직전**으로 옮기고 PHP/SEI~PLP 로 감싼다.
-- TIA 자체가 중단 불가이므로 늘어나는 IRQ 지연은 ST/LDA/STA 몇 개뿐이다.
--
--     원본     631 B · 노출 창 80 B
--     재무장   653 B · 노출 창 0 B     (ST0 #$02 바로 다음이 TIA)
--
-- 구성 (0.4.57/0.4.58/0.4.82 는 건드리지 않은 별도 체인)
-- ---------------------------------------------------------------------------
--     0.4.89-vdc-rearm            ← 이 파일.  진입점
--      └ 0.4.48 fragment/end wipe
--         └ 0.4.89-marker         count_ok 표식
--            └ 0.4.89-stage       stage 재무장 ($5D8D · 표에서 읽는다)
--               └ 0.4.89-controller  오프셋 표를 읽어 SUB_VOICE_* 를 세운다
--                  └ 0.4.31        AC 적재 · 키 매칭 · Lua 조각 타이머
--
-- 엔진을 안 구웠으면 먼저 굽는다:
--     python tools/build_subtitle_engine_vdc_rearm.py
--
-- 판정 (국장실까지 가서 본다)
-- ---------------------------------------------------------------------------
--     위 그림 번쩍임이 사라지면   래치 경합 확정.  출하 경로에 넣는다
--     떨림이 남으면               별개 원인.  업로드를 여러 VBlank 로 쪼갠다
--     둘 다 남으면                셋업 창 밖에 원인이 하나 더 있다
--
-- 이번에는 **한 글자가 아니라 19 글자 정상 엔진**이다.  자막은 온전히 보여야
-- 하고, WIPE 칸 수도 글자 수만큼 나오는 것이 정상이다.
--
-- Power Cycle 뒤 이 파일 하나만 로드한다.

-- ★ 0.4.48 의 forceRenderer 는 엔진을 고정 오프셋(+144/+146/+255/+260)으로 직접
-- 패치한다.  그 값들은 631 B 원본 기준이고, 재무장 엔진에서는 그 자리가 전부
-- 다른 코드다 (+144 는 이제 glyph_loop 안이다).  켜면 조용히 코드를 부순다.
-- 지금 체인은 둘 다 안 쓰지만, 나중에 켜는 순간 원인 못 찾는 고장이 되므로 막는다.
assert(rawget(_G, 'SUB_FRAGMENT_FORCE_KEY') == nil and
       rawget(_G, 'SUB_FRAGMENT_FORCE_BASE') == nil,
       '0.4.89 재무장 엔진에서는 SUB_FRAGMENT_FORCE_KEY/BASE 를 쓸 수 없다 ' ..
       '(0.4.48 forceRenderer 의 오프셋이 631 B 기준이다)')

