--                         -> 다음은 A 안에서 다시 이분한다
--                            (VRAM 전송 / SATB 푸시 / VCE 팔레트 / $5B80 점유)
--     번쩍임이 남으면     원인은 B -- 그리지도 않는데 화면이 깨진다는 뜻이다
--                         -> $5B80 점유나 $22A6 쓰기처럼 "적재만" 하는 쪽이다
--                            (이 경우가 더 중요하다.  아무도 안 재본 곳이다)
