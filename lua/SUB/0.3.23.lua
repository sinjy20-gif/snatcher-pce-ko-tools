-- SUB 0.3.23 -- reception pattern $00B2 repair POC.
-- 0.3.21/0.3.22 proved that no-skip and skip have identical AC state,
-- CPU cache and SATB.  Of every live reception sprite, only pattern $00B2
-- differs: no-skip leaves its lower half dirty.  Patch that one pattern only.

local MEM  = emu.memType.pceMemory
local VRAM = emu.memType.pceVideoRam
local CPU  = emu.memType.cpu
local armed, done = false, false

-- Exact 128-byte pattern $00B2 captured from the clean skip route.
local CLEAN = {
  0xFF,0xFF,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
  0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
  0xFF,0xFF,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
  0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
  0xFF,0xFF,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
  0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
  0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
  0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
}

emu.addMemoryCallback(function()
  if armed or done then return end
  local ptr = (emu.read(0x3471, MEM) or 0) | ((emu.read(0x3472, MEM) or 0) << 8)
  if ptr ~= 0x3499 and ptr ~= 0x349A then return end
  -- $66E5 is the renderer entry.  Apply at endFrame so any upload performed
  -- by that renderer cannot overwrite the repair later in the same frame.
  armed = true
end, emu.callbackType.exec, 0x66E5, 0x66E5, emu.cpuType.pce, CPU)

emu.addEventCallback(function()
  if not armed or done then return end
  done = true
  local changed = 0
  for i = 0, 127 do
    if (emu.read(0x2C80 + i, VRAM) or 0) ~= CLEAN[i + 1] then changed = changed + 1 end
    emu.write(0x2C80 + i, CLEAN[i + 1], VRAM)
  end
  emu.log(string.format('SUB 0.3.23 REPAIR PASS: pattern $00B2 · changed=%d/128 B', changed))
  emu.log('  접수처 액션 UI가 정상인지 확인할 것')
end, emu.eventType.endFrame)

emu.log('SUB 0.3.23 loaded -- reception pattern B2 repair POC')
emu.log('  노스킵 접수처에서 액션 메뉴를 열거나 커서를 움직일 것')
