-- SUB 0.4.63-forcebase-1700 -- 0.4.62 그대로 + allocator base 를 $1700 으로 고정
--
-- ── 왜 (2026-08-29 오전 VRAM 점유 지도 + 0.4.62 실행) ─────────────────────
--
-- 0.4.62 정주행에서 KEY #11 `00F00E800041` 에 allocator 가 base=$3F80 을 골랐고
-- 그 화면이 깨졌다.  블록은 $3F80-$443F ($4C0) 다.
--
-- 같은 날 오전에 VDC 포트 재구성으로 뜬 VRAM 점유 지도
-- (dump/sub_0_4_56_vram_map_20260829_093802.tsv) 는 그 자리를 이렇게 적었다:
--
--     3900-3FEF   mask 0x15 = 써짐 + BAT + **음성 창 중 BAT 참조**
--     3FF0-3FFF   mask 0x01 = 써짐
--     4000-5F7F   mask 0x2B = 써짐 + **음성 창 중 써짐** + SATB + **음성 창 중 SATB**
--
-- 즉 $3F80 블록은 $3FF0-$3FFF 16 word 를 빼면 전부 **음성 창 동안 게임이 쓰거나
-- 참조하는 땅**이다.  allocator 의 순간 스캔은 고른 시점에만 비어 있으면 통과
-- 시키므로 이런 자리를 막지 못한다.  이건 0.3.42-wide 헤더가 이미 적어둔
-- "고른 뒤에 게임이 같은 자리를 가져갔다" 와 같은 실패다.
--
-- 반대로 같은 지도에서 이 구간은 6 비트 전부 0 이었다:
--
--     1700-1CFF   1536 word   쓰기 0 · BAT 0 · SATB 0
--
-- 필요한 0x4C0 (1216 word) 이 들어가고 320 word 가 남는다.  $1700 은 32 word
-- 정렬이므로 스프라이트 패턴 base 조건도 만족한다.
--
-- ── 이 파일이 하는 일 ─────────────────────────────────────────────────────
--
-- 0.4.62 체인을 **하나도 고치지 않는다.**  0.3.43-defer 가 읽는
-- SUB_ALLOCATOR_FORCE_BASE 를 미리 세워 두기만 한다.  0.4.59 는 자기가 세운
-- 전역만 지우고 FORCE_BASE 는 건드리지 않으므로 그대로 전달된다.
--
-- 따라서 이 시험은 "동적 탐색 vs $1700 고정" 한 가지만 다르다.
--
-- ── 무엇을 보나 ───────────────────────────────────────────────────────────
--
--   * KEY #11 `00F00E800041` 장면이 안 깨지는가        <- 직접 목표
--   * `PATCHED base=$1700` 만 나오고 다른 base 가 안 나오는가
--   * `게임이 가져갔다` 로그가 줄어드는가
--   * 조각이 여러 개인 자막에서 글자가 겹치거나 남지 않는가
--
-- 주의: 지도는 캡슐 방·도시 구간 한 세션(약 12 분, 음성 창 162 개)에서 나왔다.
-- $1700-$1CFF 가 **모든 장면에서** 빈다는 증명이 아니다.  다른 장소에서
-- VRAM-map.lua 를 더 돌려 교집합을 내야 한다.  지금은 $3F80 보다 훨씬 나은
-- 자리라는 것까지가 근거다.
--
-- Power Cycle 뒤 다른 SUB Lua 없이 이 파일 하나만 실행할 것.

SUB_ALLOCATOR_FORCE_BASE = 0x1700

dofile('C:/snatcher/lua/SUB/0.4.62-reviewed-full-subtitle-audit.lua')

emu.log('SUB 0.4.63-forcebase-1700 -- allocator base 고정 $1700-$1BBF')
emu.log('  근거: 08-29 오전 VRAM 지도에서 $1700-$1CFF 는 6비트 전부 0 (1536 word)')
emu.log('  0.4.62 가 깨진 KEY #11 00F00E800041 의 base=$3F80 은 음성 창 중 사용 중이었다')
emu.log('  확인: PATCHED base 가 $1700 하나로만 나오는가 · 그 장면이 안 깨지는가')
