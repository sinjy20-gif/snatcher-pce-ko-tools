-- SUB 0.4.97 -- 와이프만 빼고 돌린다.  A/B 대조 하나.
--
-- 가설
-- ---------------------------------------------------------------------------
-- 0.4.48 와이프가 국장실 번쩍임의 범인인가.
--
-- 그럴듯한 이유:
--   · 와이프는 Lua 가 **프레임 한복판에** Sprite RAM 과 VRAM SATB 를 직접 0 으로
--     쓴다.  VDC 가 그리는 도중에 바뀌므로 그 프레임에 즉시 반영된다.
--   · pointsAtSelected 는 "팔레트 15 · 패턴이 우리 블록을 가리킴" 인 슬롯을
--     지우는데, 우리 엔진도 팔레트 15 를 쓴다.  게임 스프라이트가 같은 조건에
--     걸릴 여지가 있다.
--   · 0.4.91 은 BG 타일만 봤다.  **스프라이트 패턴**이 $1600 근처를 쓰는지는
--     아직 아무도 안 봤다.
--   · 주기가 맞는다.  와이프는 조각 전환과 음성 종료마다 돈다.
--
-- 이 판
-- ---------------------------------------------------------------------------
-- 0.4.89 체인에서 **0.4.48 만 뺀다.**  나머지는 그대로다:
--
--     0.4.89-marker      count_ok 표식 (받는 쪽이 없으니 로그만 남는다)
--      └ 0.4.89-stage    stage 재무장
--         └ 0.4.89-controller  오프셋 표 · SUB_VOICE_*
--            └ 0.4.31    AC 적재 · 키 매칭 · Lua 조각 타이머
--
-- 판정
--     번쩍임이 사라지면   와이프가 범인이다.  지우는 조건/시점을 고쳐야 한다
--     그대로면            와이프는 무죄.  다시 IRQ/스프라이트 쪽으로 간다
--
-- ★ 와이프가 없으므로 **이전 조각 자막이 화면에 남는다.**  그건 고장이 아니라
--   이 실험의 예정된 부작용이다.  판정은 오직 "배경이 튀어나오는가" 하나다.
--
-- Power Cycle 뒤 이 파일 하나만 로드한다.  국장실에서 자막 몇 개를 흘린다.

