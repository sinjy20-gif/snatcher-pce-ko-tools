-- 치환이 **빗나간 줄만** 쓸어 담는다.  0.1.0  (한 바퀴 돌면 목록이 완성된다)
--
-- 왜
-- --
-- 대부분 한글인데 플레이하다 보면 일본어가 어쩌다 하나씩 나온다.  그걸 눈으로
-- 전부 찾는 건 사실상 불가능하다 (소유자 2026-09-16: "이걸 전부 다 찾기는 어렵고").
--
-- 화면에 일본어가 남는다는 건 **치환 조회가 빗나갔다**는 뜻이다.  그 빗나감은
-- 게임 안에서 일어나므로, 그 순간을 기록하면 목록이 저절로 만들어진다.
--
--     눈으로 찾기   한 줄 볼 때마다 멈추고 적는다.  놓치면 끝
--     이 프로브     평소처럼 한 바퀴 돌면 빠진 줄이 **전부** 파일에 쌓인다
--
-- 무엇을 남기나
-- -------------
-- 조회가 miss 난 줄만 남긴다 (hit 는 안 남긴다 -- 로그가 작아진다).
--
--     state_before   게임이 조회를 시작한 state
--     source_hex     원문 바이트   <- 이것이 화면에 일본어로 뜬 그 줄이다
--     pack           팩 번호
--
-- 분석은 `tools/report_miss_sweep.py` 가 한다 -- 마스터와 대조해서
-- "그 줄이 마스터에 있는데 못 찾은 것" 인지 "번역 자체가 없는 것" 인지 가른다.
--
-- ⚠ 반드시 **부팅부터** 돌릴 것
-- ------------------------------
-- 번역 페이로드는 부팅 때 AC $000000 으로 한 번 올라가고 그 뒤 조회는 AC 에서만
-- 한다.  옛 빌드에서 뜬 세이브스테이트를 불러오면 **디스크가 새것이어도 AC 에는
-- 옛 번역이 앉아 있어서** 없는 미스가 잔뜩 잡힌다.
--
-- 쓰는 법
-- -------
--   1) Mesen 에서 이번 판을 **Power Cycle** 로 띄운다 (BIOS 와 CUE 둘 다 그 폴더로)
--   2) 이 파일을 Script 로 연다
--   3) 평소처럼 논다.  오래 돌수록 목록이 촘촘해진다
--   4) ★ Stop 을 눌러야 마지막 줄이 파일에 남는다
--
-- 산출물  C:/snatcher/snatcher_tool/logs/miss_sweep_v010.tsv
--
-- ★ 화면에 아무것도 안 그리고 게임 메모리에도 안 쓴다.  순수 관측이다.

