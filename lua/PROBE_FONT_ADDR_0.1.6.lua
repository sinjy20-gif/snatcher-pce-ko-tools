local frame, dirty = 0, false
local enters, hangulEnters, hit16, hit12 = 0, 0, 0, 0
local matched, differed = 0, 0
local leadTally = {}          -- 리드 바이트 -> 횟수.  한글이 아예 안 오는지 본다
local seenChar = {}           -- 문자마다 한 행만.  로그가 안 터지게
local seenCount = 0
local pending = nil           -- ENTRY 에서 잡아 SPLIT 에서 마무리

local function byte(a) return emu.read(a, mem) or 0 end
local function word(a) return byte(a) + byte(a + 1) * 256 end

local function mprAt(cpu)
  local ok, s = pcall(emu.getState)
  if not ok or s == nil then return nil end
  local slot = math.floor(cpu / 0x2000)
  local v = s[string.format("memoryManager.mpr[%d]", slot)]
  if v == nil then v = s[string.format("mpr[%d]", slot)] end
  return v
end

local function row(kind, code, char, idx, src, romoff, want, cmp, got, note)
  file:write(string.format("%s\t%d\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n",
    kind, frame, code or "", char or "", idx or "",
    src and string.format("%04X", src) or "",
    romoff and string.format("%06X", romoff) or "",
    want and string.format("%06X", want) or "",
    cmp or "", got or "", note or ""))
  dirty = true
end

-- EX_GETFNT 진입.  여기서는 $F9/$F8 이 아직 SJIS 원본이다 ($F1E3 이 덮기 전)
emu.addMemoryCallback(function()
  enters = enters + 1
  local lead, trail = byte(ZP + 0xF9), byte(ZP + 0xF8)
  leadTally[lead] = (leadTally[lead] or 0) + 1
  local key = string.format("%02X %02X", lead, trail)
  local hit = HANGUL[key]
  if hit == nil then pending = nil return end
  hangulEnters = hangulEnters + 1
  if seenChar[key] then pending = nil return end
  seenChar[key] = true
  seenCount = seenCount + 1
  pending = hit
end, emu.callbackType.exec, ENTRY, ENTRY, emu.cpuType.pce, mem)

-- 페이징이 끝난 지점.  src 가 가리키는 18 B 를 그대로 읽어 기대값과 맞춘다
emu.addMemoryCallback(function()
  local h = pending
  if h == nil then return end
  pending = nil

  local src = word(ZP + 0xEC)
  local ff = byte(ZP + 0xFF)
  local key = string.format("%02X %02X", byte(ZP + 0xF9), byte(ZP + 0xF8))
  local bank = mprAt(src)
  if bank == nil then
    row("hangul", key, h.c, h.i, src, nil, h.o, "NOMPR", "", "emu.getState 실패")
    return
  end
  local romoff = bank * 0x2000 + (src % 0x2000)

  local got = {}
  for k = 0, STRIDE - 1 do got[#got + 1] = string.format("%02X", byte(src + k)) end
  local gotHex = table.concat(got)

  local cmp
  if gotHex == h.e then cmp = "MATCH" matched = matched + 1
  else cmp = "DIFF" differed = differed + 1 end

  row("hangul", key, h.c, h.i, src, romoff, h.o, cmp, gotHex,
    string.format("$FF=$%02X (%s) · MPR=$%02X · romoff-want = %d · 기대 %s",
      ff, (ff % 2 == 1) and "12x12" or "16x16", bank, romoff - h.o, h.e))
end, emu.callbackType.exec, SPLIT, SPLIT, emu.cpuType.pce, mem)

emu.addMemoryCallback(function() hit16 = hit16 + 1 end,
  emu.callbackType.exec, COPY_16, COPY_16, emu.cpuType.pce, mem)
emu.addMemoryCallback(function() hit12 = hit12 + 1 end,
  emu.callbackType.exec, COPY_12, COPY_12, emu.cpuType.pce, mem)

emu.addEventCallback(function()
  frame = frame + 1
  if dirty then file:flush() dirty = false end
end, emu.eventType.endFrame)

emu.addEventCallback(function()
  local leads = {}
  for lead, n in pairs(leadTally) do
    leads[#leads + 1] = string.format("%02X:%d", lead, n)
  end
  table.sort(leads)
  row("summary", "", "", "", nil, nil, nil, "", "",
    string.format("EX_GETFNT %d 회 · 그중 한글코드 %d 회 · 문자 %d 종 · MATCH %d · DIFF %d",
      enters, hangulEnters, seenCount, matched, differed))
  row("paths", "", "", "", nil, nil, nil, "", "",
    string.format("$F1BA(16x16) %d 회 · $F2CD(12x12) %d 회", hit16, hit12))
  row("leads", "", "", "", nil, nil, nil, "", "",
    "리드바이트 분포 -- " .. table.concat(leads, " "))
  if hangulEnters == 0 then
    file:write("-- (A) 한글 코드가 EX_GETFNT 까지 오지 않았다.  BIOS 문제가 아니다\n")
  elseif differed == 0 then
    file:write("-- (B) BIOS 가 우리 갈무리 바이트를 그대로 읽어갔다.  글리프는 나갔다\n")
  else
    file:write("-- (C) 엉뚱한 자리를 읽는다.  romoff 와 want 의 차를 볼 것\n")
  end
  file:close()
end, emu.eventType.scriptEnded)

